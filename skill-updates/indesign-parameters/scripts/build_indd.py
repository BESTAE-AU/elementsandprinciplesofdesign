def main(argv):
    if len(argv) < 2:
        sys.exit(__doc__)
    size, key = argv[0].upper(), argv[1].upper()
    opt = lambda f: argv[argv.index(f) + 1] if f in argv else None
    out = os.path.abspath(os.path.expanduser(opt("--out") or f"InDesign-Parameters-{size}-{key}.indd"))
    data = spec(size, key, opt("--font"), "--sample" in argv)
    dom = opt("--domain")
    if dom:
        slugs = list(grid.DOMAINS) if dom == "all" else dom.split(",")
        for slug in slugs:
            if slug not in grid.DOMAINS:
                sys.exit(f"Unknown domain '{slug}'. Options: {', '.join(grid.DOMAINS)} or all")
            name, *sw = grid.DOMAINS[slug]
            data["domains"].append({"name": name, "swatches": [{"name": n, "hex": h} for n, h in sw]})
    jsx = JSX.replace("__SPEC__", json.dumps(data)).replace("__OUT__", json.dumps(out))
    jsx_path = out[:-5] + ".jsx"
    with open(jsx_path, "w", encoding="utf-8-sig") as f:
        f.write(jsx)
    print(f"Wrote {jsx_path}")
    if "--run" in argv:
        script = (f'tell application id "com.adobe.InDesign" to do script (POSIX file "{jsx_path}") '
                  f'language javascript')
        res = subprocess.run(["osascript", "-e", script], capture_output=True, text=True, timeout=600)
        print(res.stdout.strip() or res.stderr.strip())
        log = out[:-5] + "-build-log.txt"
        if os.path.exists(log):
            print(open(log, encoding="utf-8").read())


if __name__ == "__main__":
    main(sys.argv[1:])
