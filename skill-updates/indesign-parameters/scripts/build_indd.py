#!/usr/bin/env python3
"""Generate (and optionally run) an InDesign ExtendScript that builds a document with the full
InDesign Parameters system: grid, swatches, paragraph/character/object/cell/table styles, panels,
parent-page furniture, and (with --sample) a two-page sample layout.

Usage:
  python3 build_indd.py A4P A --out ~/Desktop/Sample.indd [--sample] [--run] [--font Lato] [--domain slug|slug,slug|all]

--run executes it in InDesign via osascript (macOS) and writes a log next to the .indd.
Without --run, the .jsx is written next to the output so it can be run from InDesign's Scripts panel.
Print sizes only (A4P, A4L, A3P, A3L).
"""
import json
