import grid  # noqa: E402


def spec(size, key, font=None, sample=False):
    if size in grid.DIGITAL:
        sys.exit("build_indd.py builds print documents (A4P, A4L, A3P, A3L) only.")
    name, W, H = grid.SIZES[size]
    c, cg, r, rg, L, R, bi, bo, bc, T, B = grid.PRESETS[size][key]
    family, entry = grid.font_entry(font)
    heavy, light = entry["heavy"], entry["light"]
    bold = "Bold" if "Bold" in entry["weights"] else heavy
    pitch_mm = r + rg
    pitch_pt = pitch_mm * grid.MM_TO_PT

    headings = []
    for hname, lines, rows in grid.TYPE_STYLES:
        weight = light if hname == "Subheading" else heavy
        cap = (grid.span(r, rg, rows) - (lines - 1) * rg) / lines
        if cap < grid.MIN_CAP["mm"]:
            continue  # too small / impossible on this preset: style isn't created
        headings.append({"name": hname, "weight": weight,
                         "size": round(cap / entry["weights"][weight]["cap"] * grid.MM_TO_PT, 1),
                         "leading": round((cap + rg) * grid.MM_TO_PT, 1)})

    bodies = {}
    for bname, pt, target, rng, track in grid.BODY_STYLES:
        fit = grid.body_fit(pitch_pt, pt, target, rng)
        bodies[bname] = {"size": pt, "leading": fit[2] if fit else round(pt * 1.35, 1), "tracking": track}

    lp, la, lr = grid.LEAD["print"]
    lead_fit = grid.body_fit(pitch_pt, lp, la, lr, False, grid.LEAD_ROWS)
    qp, qa, qr = grid.PULL_QUOTE["print"]
    q_fit = grid.body_fit(pitch_pt, qp, qa, qr, False, grid.LEAD_ROWS)
    ans = grid.answer_lines(pitch_mm)

    return {
        "size": size, "preset": key, "sizeName": name, "W": W, "H": H,
        "margins": {"top": T, "bottom": B, "left": L, "right": R},
        "col": c, "cg": cg, "row": r, "rg": rg,
        "font": family, "heavy": heavy, "light": light, "bold": bold,
        "capRatios": {w: v["cap"] for w, v in entry["weights"].items()},
        "headings": headings, "bodies": bodies,
        "lead": {"size": lp, "leading": lead_fit[2] if lead_fit else round(lp * 1.3, 1)},
        "pullQuote": {"size": qp, "leading": q_fit[2] if q_fit else round(qp * 1.25, 1)},
        "answer": {"leading": ans[2] if ans else bodies["Body"]["leading"] * 2},
        "indent": grid.INDENT["print"],
        "styleLibrary": [{"folder": f, "name": n, "first": s, "span": k} for f, n, s, k in grid.STYLE_LIBRARY],
        "sample": sample,
        "domains": [],
    }


